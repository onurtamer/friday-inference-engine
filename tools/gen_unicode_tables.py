"""Generate unicode_tables.h: codepoint ranges for Unicode letters (L*) and
numbers (N*), used by the Qwen2 pre-tokenizer. Usage: python gen_unicode_tables.py <out.h>"""
import sys
import unicodedata


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        ok = pred(unicodedata.category(chr(cp)))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1)); start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


L = ranges(lambda c: c.startswith("L"))
N = ranges(lambda c: c.startswith("N"))
with open(sys.argv[1], "w", newline="\n") as f:
    f.write("// Generated by tools/gen_unicode_tables.py from Python unicodedata "
            f"(Unicode {unicodedata.unidata_version}). Do not edit.\n#pragma once\n#include <cstdint>\n\n")
    for name, rs in (("kUnicodeLetterRanges", L), ("kUnicodeNumberRanges", N)):
        f.write(f"static const uint32_t {name}[][2] = {{\n")
        for a, b in rs:
            f.write(f"    {{0x{a:X}, 0x{b:X}}},\n")
        f.write("};\n\n")
print(f"letters: {len(L)} ranges, numbers: {len(N)} ranges, unicode {unicodedata.unidata_version}")
